export const GLYPH_W = 5;
export const GLYPH_H = 7;
export const CHAR_ADVANCE = 6;
export const LINE_HEIGHT = 12;

// Pre-decode every glyph into a flat Uint8Array of on/off pixels.
const BITS = new Map();
for (const [ch, rows] of Object.entries(GLYPHS)) {
  const cells = new Uint8Array(GLYPH_W * GLYPH_H);
  rows.split(' ').forEach((row, y) => {
    for (let x = 0; x < GLYPH_W; x++) if (row[x] === '1') cells[y * GLYPH_W + x] = 1;
  });
  BITS.set(ch, cells);
}
const FALLBACK = BITS.get('?');

/** Width in pixels of a single line of text. */
export function textWidth(str) {
  return str.length === 0 ? 0 : str.length * CHAR_ADVANCE - 1;
}

/**
 * Draw text at (x, y) where y is the top of the glyph box.
 * `shadow` paints a 1px offset copy first, which is how the GBA UI reads.
 */
export function drawText(ctx, str, x, y, color = '#38404a', shadow = '#b8c0c8') {
  const text = String(str);
  if (shadow) paint(ctx, text, x + 1, y + 1, shadow);
  paint(ctx, text, x, y, color);
}

function paint(ctx, str, x, y, color) {
  ctx.fillStyle = color;
  for (let i = 0; i < str.length; i++) {
    const cells = BITS.get(str[i]) || FALLBACK;
    const ox = x + i * CHAR_ADVANCE;
    for (let gy = 0; gy < GLYPH_H; gy++) {
      let run = 0;
      for (let gx = 0; gx <= GLYPH_W; gx++) {
        const on = gx < GLYPH_W && cells[gy * GLYPH_W + gx];
        if (on) { run++; continue; }
        if (run) { ctx.fillRect(ox + gx - run, y + gy, run, 1); run = 0; }
      }
    }
  }
}

/** Greedy word wrap to a pixel width, returning an array of lines. */
export function wrapText(str, maxWidth) {
  const words = String(str).split(' ');
  const lines = [];
  let line = '';
  for (const word of words) {
    const candidate = line ? line + ' ' + word : word;
    if (textWidth(candidate) <= maxWidth || !line) line = candidate;
    else { lines.push(line); line = word; }
  }
  if (line) lines.push(line);
  return lines;
}
